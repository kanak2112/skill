export const inr = (n, digits = 0) =>
  `₹${n.toLocaleString('en-IN', { minimumFractionDigits: digits, maximumFractionDigits: digits })}`;

export function formatWait(mins) {
  if (!mins) return 'Immediate stream';
  if (mins < 60) return `Waiting list: ${mins} mins`;
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  return `Waiting list: ${h}h ${String(m).padStart(2, '0')}m`;
}

export function matchesQuery(model, query) {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  const hay = [model.title, model.expert, model.keywords, model.domain].filter(Boolean).join(' ').toLowerCase();
  // Match on any meaningful word so natural phrases ("knife skill for cutting fish") still find results.
  const words = q.split(/\s+/).filter((w) => w.length > 2 && !['for', 'the', 'and', 'find', 'skill', 'skills', 'with'].includes(w));
  if (!words.length) return hay.includes(q);
  return words.some((w) => hay.includes(w.replace(/s$/, '')));
}
