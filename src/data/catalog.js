export const inr = (n, digits = 0) =>
  `₹${n.toLocaleString('en-IN', { minimumFractionDigits: digits, maximumFractionDigits: digits })}`;

export function formatWait(mins) {
  if (!mins) return 'Immediate stream';
  if (mins < 60) return `Waiting list: ${mins} mins`;
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  return `Waiting list: ${h}h ${String(m).padStart(2, '0')}m`;
}
